/// <summary>Parses icon path data into a (cached, shared) geometry for PathIcon.Data.</summary>
public sealed class IconGeometryConverter : IValueConverter
{
    public static readonly IconGeometryConverter Instance = new();

    private static readonly ConcurrentDictionary<string, Geometry> Cache = new(StringComparer.Ordinal);

    public static Geometry? Parse(string? data)
    {
        if (string.IsNullOrWhiteSpace(data)) return null;
        if (Cache.TryGetValue(data, out var cached)) return cached;
        try
        {
            var geometry = StreamGeometry.Parse(data);
            Cache[data] = geometry;
            return geometry;
        }
        catch (Exception ex) when (ex is FormatException or InvalidOperationException or ArgumentException)
        {
            return null;
        }
    }

    public object? Convert(object? value, Type targetType, object? parameter, CultureInfo culture) => Parse(value as string ?? parameter as string);

    public object? ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture) => throw new NotSupportedException();
}

